def package_energy(gamma_list, beta, T):
    """Compute D and B for the equal-real-part package with cut-off T on beta.

    Args:
      gamma_list: list of positive imaginary parts of zeta zeros on critical line.
      beta: common real part of the zeros (e.g., 1/2 for RH).
      T: height cut-off (we include zeros with gamma <= T).

    Returns:
      D (diagonal energy, with conjugates counted),
      B (off-diagonal budget, with conjugates).
    """
    gammas = [g for g in gamma_list if g <= T]
    N_pos = len(gammas)
    N_total = 2 * N_pos  # count both + and - imaginary parts

    # Diagonal energy: D = sum m(ρ)^2 / |ρ|^2 = sum 1/(beta^2 + gamma^2).
    # We include both positive and negative imaginary parts.
    D_single = sum(1.0 / (beta * beta + g * g) for g in gammas)
    D = 2.0 * D_single

    # Off-diagonal budget: B = sum_{rho, rho' distinct} 2 / (|rho| * |rho'| * |Im rho - Im rho'|)
    # With conjugation pairs: there are 4 "types" of pair:
    #   (+, +): gap = |gamma_i - gamma_j|
    #   (+, -): gap = gamma_i + gamma_j
    # Each pair counted in both (+, +) and (+, -).
    B_pp = 0.0  # (+, +) and (-, -)
    B_pm = 0.0  # (+, -) and (-, +)
    for i, gi in enumerate(gammas):
        ni = math.sqrt(beta * beta + gi * gi)
        for j, gj in enumerate(gammas):
            if i == j:
                continue
            nj = math.sqrt(beta * beta + gj * gj)
            gap_pp = abs(gi - gj)
            gap_pm = gi + gj
            B_pp += 2.0 / (ni * nj * gap_pp)
            B_pm += 2.0 / (ni * nj * gap_pm)
    B = B_pp + B_pm
    return D, B


