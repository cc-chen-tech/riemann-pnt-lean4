"""Windowed detector feasibility: frequency-weighted complementary contribution.

The current Lean detector (`HalfIsolatedSimplifiedDetectorInput T` in
HalfIsolatedZeroDichotomy/Audit.lean) forces existence of a top-layer zero
with NO height window: its complementary envelope
exp((beta - gap) y) * C * (1 + log(T+6))^2 is frequency-independent.

A height-windowed detector (gap diagnosis, Gap 1/2) needs, at a detection
frequency gamma in a window [T0, T0+H], a bound on the frequency-weighted
complementary-layer contribution

    S(gamma) = sum over complementary zeros rho (real part <= beta - gap,
               |im| <= T) of  m(rho) / (|rho| * |gamma - im rho|).

Toy model: complementary zeros with uniform/Poisson imaginary parts at the
global-count density log T / (2 pi).  We measure S(gamma) over a gamma grid
in [T0, T0+H]: its mean, max, and the fraction of "bad" points exceeding
the mean by a factor, versus T and the window exponent h (H = T^h).

The seed response at the aligned frequency is x^beta * lam * log X / |rho_0|,
so the comparison exponent is x^gap * log X / T0 against S(gamma).  With the
mean bound S ~ log^2 T / (H) the windowed detector is feasible whenever
gap > 0; this experiment checks the mean/max scaling.  Toy model only.
"""

import math
from pathlib import Path

import numpy as np

OUT = Path(__file__).resolve().parent / "output"
OUT.mkdir(parents=True, exist_ok=True)


def complementary_pts(kind, T, rng):
    if kind == "grid":
        s = 2 * math.pi / math.log(T)
        return np.arange(0.0, T, s)
    if kind == "poisson":
        lam = math.log(T) / (2 * math.pi)
        n = rng.poisson(lam * T)
        return np.sort(rng.uniform(0.0, T, max(n, 0)))
    raise ValueError(kind)


def S_at(gamma, pts):
    d = np.abs(pts - gamma)
    d = np.where(d == 0.0, np.finfo(float).eps, d)
    return float(np.sum(1.0 / (pts * d)))


def main():
    rng = np.random.default_rng(7)
    lines = ["# Windowed detector: frequency-weighted complementary contribution",
             "",
             "Generated by `experiments/gate_budget/windowed_detector.py`.",
             "Toy model only; not a theorem.", ""]

    for kind in ["grid", "poisson"]:
        lines.append(f"## complementary zeros: {kind} (density log T / 2pi)")
        lines.append("")
        lines.append("| T | H = T^h | mean S | max S | bad-fraction (>10x mean) |")
        lines.append("|---|---------|--------|-------|---------------------------|")
        for T in [1e4, 1e5, 1e6]:
            pts = complementary_pts(kind, T, rng)
            for h in [0.2, 0.4, 0.6]:
                H = T ** h
                T0 = T / 2
                n_grid = 200
                # offset by half a spacing so detection points avoid the
                # complementary zeros (the choice lemma selects such gamma)
                s = 2 * math.pi / math.log(T)
                gammas = np.linspace(T0 + s / 2, T0 + H, n_grid)
                vals = np.array([S_at(g, pts) for g in gammas])
                mean_s = float(vals.mean())
                max_s = float(vals.max())
                bad = float(np.mean(vals > 10 * mean_s))
                lines.append(
                    f"| {T:.0e} | {H:.1e} | {mean_s:.3e} | {max_s:.3e} | {bad:.3f} |"
                )
        lines.append("")
        # scaling fit: log mean S vs log T at h = 0.4
        xs, ys = [], []
        for T in [3e3, 1e4, 3e4, 1e5, 3e5, 1e6]:
            pts = complementary_pts(kind, T, rng)
            H = T ** 0.4
            gammas = np.linspace(T / 2, T / 2 + H, 100)
            vals = np.array([S_at(g, pts) for g in gammas])
            xs.append(math.log(T))
            ys.append(math.log(vals.mean()))
        slope = float(np.polyfit(xs, ys, 1)[0])
        lines.append(f"- fitted exponent of mean S at h=0.4: {slope:+.3f} "
                     f"(target: -1 plus log factors, since the 1/|rho| weight")
        lines.append("  already decays like 1/T at height T0 = T/2; the window")
        lines.append("  exponent h only affects the choice-lemma margin)")
        lines.append("")

    lines.append("## Interpretation")
    lines.append("")
    lines.append("- If mean S scales like T^-(1-h) polylog, the windowed detector")
    lines.append("  threshold is beaten by the aligned seed response")
    lines.append("  x^gap * log X / T0 for every gap > 0: the window H dilutes the")
    lines.append("  frequency-weighted complementary mass.")
    lines.append("- max S and the bad fraction control the detection-point choice")
    lines.append("  lemma (there exists gamma in the window with S(gamma) small);")
    lines.append("  the bad fraction must stay bounded away from 1.")
    lines.append("")
    report = OUT / "windowed_detector_report.md"
    report.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {report}")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
