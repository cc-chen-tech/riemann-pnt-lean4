"""Toy iteration model for the half-isolated directed packet.

Simulates the successor relation behind `halfIsolatedDirectedNext`
(worktree exceptional-zero-amplification-integration,
PrimeNumberTheorem/HalfIsolatedZeroDichotomy/Audit.lean):

    halfIsolatedDirectedNext(T, beta, delta, rho)
      = { sigma in top layer : |sigma.im - rho.im| <= delta, sigma.im > rho.im }.

On synthetic top-layer sets (all with real part beta, imaginary parts in
[0, T]) this measures, as a function of T and the local-density model, the
per-node branching count and the growth exponent of the reachable set from a
single seed.  Toy model only; not a theorem.

Density models (all satisfy the global-count shape |Gamma| <= O(T log T)):
  grid     regular lattice, spacing s(T) = 2*pi/(c*log T)
  poisson  Poisson with intensity a*log(T)/(2*pi)
  cluster  grid base plus a dense cluster of factor m around the seed

The global-count constraint caps the average density at O(log T), so the
branching exponent kappa of q(T) ~ T^kappa is expected to be 0 for grid and
poisson models (per-node branching bounded), while the cluster model shows
what a super-logarithmic local density would deliver.
"""

import math
import random
from pathlib import Path

import numpy as np

OUT = Path(__file__).resolve().parent / "output"
OUT.mkdir(parents=True, exist_ok=True)


def build_top_layer(kind, T, seed, delta, c=1.0, a=1.0, m=50.0, rng=None):
    """Return sorted numpy array of imaginary parts in [0, T]."""
    if kind == "grid":
        s = 2 * math.pi / (c * math.log(T))
        pts = np.arange(0.0, T, s)
    elif kind == "poisson":
        lam = a * math.log(T) / (2 * math.pi)
        n = rng.poisson(lam * T)
        pts = np.sort(rng.uniform(0.0, T, max(n, 0)))
    elif kind == "cluster":
        s = 2 * math.pi / (c * math.log(T))
        base = np.arange(0.0, T, s)
        # dense cluster around the seed with intra-cluster spacing delta/m
        lo = max(0.0, seed - 20 * delta)
        hi = min(T, seed + 20 * delta)
        extra = np.arange(lo, hi, delta / m)
        pts = np.sort(np.concatenate([base, extra]))
    else:
        raise ValueError(kind)
    return pts


def successors(gamma, pts, delta):
    """Indices of pts in (gamma, gamma + delta]."""
    lo = np.searchsorted(pts, gamma, side="right")
    hi = np.searchsorted(pts, gamma + delta, side="right")
    return lo, hi


def iterate(pts, seed, delta, max_layers=None):
    """Directed window iteration from a single seed.

    Returns (layers, reached) where layers[k] is the number of distinct
    points first reached at depth k, and reached is the total distinct count.
    """
    if max_layers is None:
        max_layers = max(2, int(math.ceil(len(pts) / max(delta, 1e-9))))
    reached = {seed}
    frontier = {seed}
    layers = [1]
    for _ in range(max_layers):
        nxt = set()
        for g in frontier:
            lo, hi = successors(g, pts, delta)
            for idx in range(lo, hi):
                p = float(pts[idx])
                if p not in reached:
                    nxt.add(p)
        if not nxt:
            break
        reached |= nxt
        frontier = nxt
        layers.append(len(nxt))
    return layers, len(reached)


def max_gap(pts):
    """Largest gap between consecutive points."""
    if len(pts) < 2:
        return float("inf")
    return float(np.max(np.diff(pts)))


def density_ratio(pts, seed, radius):
    """Local density around seed divided by global density."""
    n_local = int(np.sum((pts >= seed - radius) & (pts <= seed + radius)))
    local = n_local / (2 * radius)
    global_ = len(pts) / (pts[-1] - pts[0] + 1e-30)
    return local / global_


def min_branch(pts, delta):
    """Minimum number of successors over points that have at least one."""
    best = None
    for g in pts:
        lo, hi = successors(float(g), pts, delta)
        k = hi - lo
        if k > 0:
            best = k if best is None else min(best, k)
    return best if best is not None else 0


