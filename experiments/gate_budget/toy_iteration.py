    deltas = [1.0, 10.0, 100.0]

    for kind in ["grid", "poisson", "cluster"]:
        lines.append(f"## Model: {kind}")
        lines.append("")
        lines.append("| T | delta | max gap | density ratio | reached (ratio of T) | layers |")
        lines.append("|---|-------|---------|---------------|----------------------|--------|")
        for T in Ts:
            seed = T / 2
            pts = build_top_layer(kind, T, seed, max(deltas), rng=rng)
            mg = max_gap(pts)
            dr = density_ratio(pts, seed, 20 * max(deltas))
            for delta in deltas:
                layers, reached = iterate(pts, seed, delta)
                lines.append(
                    f"| {T:.1e} | {delta:g} | {mg:.3g} | {dr:.3g} | "
                    f"{reached} ({reached / T:.3f}) | {len(layers)} |"
                )
        lines.append("")
        # exponent fits over T
        xs = [math.log(T) for T in Ts]
